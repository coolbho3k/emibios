//! Build-time generator: emits the affine sine LUT as GBA assembly data.
//!
//! sine_lut[n] = trunc(16384 * sin(2*pi*n/256)) for n = 0..255 (callers mask the index).
const std = @import("std");
const Io = std.Io;

const N = 256;
const sine_lut: [N]i16 = blk: {
    @setEvalBranchQuota(1 << 20);
    var t: [N]i16 = undefined;
    for (0..256) |n| {
        const x: f128 = 2.0 * std.math.pi * @as(f128, @floatFromInt(n)) / 256.0;
        t[n] = @intFromFloat(16384.0 * @sin(x)); // truncate toward zero
    }
    break :blk t;
};

fn build(gpa: std.mem.Allocator) ![]u8 {
    var aw = Io.Writer.Allocating.init(gpa);
    const p = &aw.writer;
    try p.writeAll(
        \\@ Generated by tools/gen/sine_lut.zig
        \\    .balign 2
        \\sine_lut:
        \\
    );
    for (sine_lut, 0..) |v, i| {
        if (i % 16 == 0) try p.writeAll("    .hword ");
        try p.print("{d}{s}", .{ v, if (i % 16 == 15 or i == N - 1) "\n" else ", " });
    }
    return aw.written();
}

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(gpa);
    const src = try build(gpa);
    if (args.len >= 2 and !std.mem.eql(u8, args[1], "--stdout")) {
        const path = try std.fs.path.join(gpa, &.{ args[1], "sine_lut.s" });
        try Io.Dir.cwd().writeFile(io, .{ .sub_path = path, .data = src });
    } else {
        var ow: Io.File.Writer = .init(.stdout(), io, &.{});
        try ow.interface.writeAll(src);
        try ow.interface.flush();
    }
}
